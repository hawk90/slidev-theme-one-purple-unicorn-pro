#!/usr/bin/env node
// layouts.json: the theme's contract, generated from the components
// themselves, for tools and agents that write decks (the lint CLI, the
// authoring skill, llms.txt):
//
//   { layouts: { name: { description, props: { prop: { type, default, required, description } } } },
//     components: { Name: { … the same … } } }
//
//   node scripts/gen-manifest.mjs           # write layouts.json
//   node scripts/gen-manifest.mjs --check   # exit 1 when layouts.json is stale
//
// Each SFC is loaded through Vite (SSR) and its runtime `props` read, so
// props built by helpers (utils/layout-props.ts) come out right; @slidev/client
// is stubbed. Descriptions: the template's first comment, and the comment
// right before each prop in the source.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createServer } from 'vite'
import vue from '@vitejs/plugin-vue'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const out = path.join(root, 'layouts.json')

// @slidev/client: whatever names the components import, as harmless stubs
const stub = {
  name: 'stub-slidev-client',
  enforce: 'pre',
  resolveId: id => (id === '@slidev/client' ? '\0slidev-client' : null),
  load: id => (id === '\0slidev-client'
    ? ['configs', 'onSlideEnter', 'onSlideLeave', 'resolveAssetUrl', 'useNav', 'useSlideContext', 'sharedState', 'useDarkMode', 'useIsSlideActive']
        .map(n => `export const ${n} = n === 'configs' || n === 'sharedState' ? {} : () => ({})`.replace(/n === '(\w+)'/g, (_, k) => String(k === n)))
        .join('\n')
    : null),
}

const comment = (raw = '') => raw.replace(/^\s*(\/\*\*?|\/\/|\*\/|\*)\s?/gm, '').replace(/\*\/\s*$/, '').replace(/\s+/g, ' ').trim()

/** The template's first <!-- comment -->: what the component is */
function description(src) {
  const t = /<template>\s*<!--([^]*?)-->/.exec(src)
  return t ? comment(t[1]) : ''
}

/**
 * The comment right before `key:` in the source: // lines, or one /** *\/
 * block (it may end on the prop's own line); never across another prop
 */
function propDoc(src, key) {
  const re = new RegExp(`((?:[ \\t]*//[^\\n]*\\n)+|[ \\t]*/\\*\\*?(?:(?!\\*/)[^])*\\*/[ \\t]*\\n?)[ \\t]*['"]?${key}['"]?\\s*:`)
  const m = re.exec(src)
  return m ? comment(m[1]) : ''
}

// The README's tables, for what a layout or component is when its template
// doesn't say: the row whose first cell names it (`a`, `b` | what they are | …)
const readme = fs.readFileSync(path.join(root, 'README.md'), 'utf8')
function readmeRow(name) {
  for (const line of readme.split('\n')) {
    if (!line.startsWith('| ')) continue
    const [first, second] = line.split(' | ')
    if (first.includes(`\`${name}\``) || first.includes(`\`<${name}>\``)) return comment(second ?? '').replace(/`/g, '')
  }
  return ''
}

const typeName = t => (Array.isArray(t) ? t.map(typeName).join(' | ') : t?.name ?? (t === null ? 'any' : String(t)))

function describeProps(props, src) {
  const outProps = {}
  const list = Array.isArray(props) ? Object.fromEntries(props.map(p => [p, {}])) : props ?? {}
  for (const [key, def] of Object.entries(list).sort(([a], [b]) => a.localeCompare(b))) {
    const d = def && typeof def === 'object' && !Array.isArray(def) && ('type' in def || 'default' in def || 'required' in def) ? def : { type: def }
    let value = d.default
    if (typeof value === 'function' && typeName(d.type) !== 'Function') value = value()
    const entry = { type: typeName(d.type ?? null) }
    if (value !== undefined) entry.default = value
    if (d.required) entry.required = true
    const doc = propDoc(src, key)
    if (doc) entry.description = doc
    outProps[key] = entry
  }
  return outProps
}

const server = await createServer({
  root,
  configFile: false,
  logLevel: 'error',
  appType: 'custom',
  server: { middlewareMode: true, hmr: false },
  optimizeDeps: { noDiscovery: true, include: [] },
  plugins: [stub, vue()],
})

const manifest = { $comment: 'Generated by scripts/gen-manifest.mjs from the components; do not edit', layouts: {}, components: {} }
try {
  for (const [dir, key] of [['layouts', 'layouts'], ['components', 'components']]) {
    for (const file of fs.readdirSync(path.join(root, dir)).filter(f => f.endsWith('.vue')).sort()) {
      const src = fs.readFileSync(path.join(root, dir, file), 'utf8')
      const mod = await server.ssrLoadModule(`/${dir}/${file}`)
      const name = file.replace(/\.vue$/, '')
      manifest[key][name] = { description: description(src) || readmeRow(name), props: describeProps(mod.default?.props, src) }
    }
  }
}
finally {
  await server.close()
}

const text = `${JSON.stringify(manifest, null, 2)}\n`
if (process.argv.includes('--check')) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : ''
  if (current !== text) {
    console.error('[manifest] layouts.json is stale: run `npm run manifest`')
    process.exit(1)
  }
  console.log('[manifest] up to date')
}
else {
  fs.writeFileSync(out, text)
  console.log(`[manifest] ${Object.keys(manifest.layouts).length} layouts, ${Object.keys(manifest.components).length} components → layouts.json`)
}
